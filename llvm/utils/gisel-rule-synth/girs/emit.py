# ---------------------------------------------------------- selection ---

ONE_USE_SUFFIX = '_1u'


def widened_bits(rule):
    """See synth.widened_width."""
    return synth.widened_width(ir.from_json(rule['source_json']),
                               ir.from_json(rule['replacement_json']))


def one_use_variant(rule):
    """The variant of ``rule`` that applies only if no interior value of
    the source has another user, or None if the rule has that guard or does
    not need it.

    A rule removes the interior operations of its source only if they have
    no other user. If the replacement costs as much as the root alone, the
    rule removes nothing from a source with a shared interior value: it
    only changes the code, and the changed code can be worse for the
    target. `select` measures the two variants and keeps one of them."""
    if rule['needs_one_use'] or rule['cost']['replacement'] == 0 or \
            rule.get('region') or \
            not ir.interior_nodes(ir.from_json(rule['source_json'])):
        return None
    v = dict(rule)
    v['id'] = rule['id'] + ONE_USE_SUFFIX
    v['needs_one_use'] = True
    v['variant_of'] = rule['id']
    return v


def candidates(db, target=None):
    """Rules a target may select (any target if ``target`` is None): proved,
    cheaper than their source under the generic cost model, and not
    dominated by a rule with the same source. A rule that moves an operation
    to a wider type is a candidate only if that type is not wider than the
    registers of the target (Target.native_bits). Each rule is followed by
    its one-use variant, if it has one. The rules are ordered as the
    combiner tries them: the rule that removes the most first, then the
    smaller source pattern."""
    bits = target.native_bits if target else targets.NATIVE_BITS
    out = [r for r in db['rules']
           if r['semantic_status']['kind'] == 'verified_refinement' and
           (r['class'] == 'reduces_cost' or
            (r['class'] == 'widens_operation' and
             r['cost']['replacement'] < r['cost']['source'] and
             widened_bits(r) <= bits)) and
           r['disjuncts'] and 'dominated_by' not in r]
    # A rule with several outputs applies only if a value below the root
    # has another user; it comes before the rule of the root alone.
    out.sort(key=lambda r: (not r.get('region'),
                            r['cost']['replacement'] - r['cost']['source'],
                            r['cost']['source'], r['id']))
    res = []
    for r in out:
        res.append(r)
        v = one_use_variant(r)
        if v:
            res.append(v)
    return res


def load_profiles(profile_dir=None):
    """Target name -> profile, for every profile file that exists."""
    out = {}
    for name, t in sorted(targets.TARGETS.items()):
        path = os.path.join(profile_dir, name + '.json') if profile_dir \
            else t.profile_path
        if os.path.exists(path):
            with open(path) as f:
                out[name] = json.load(f)
    return out


def selection(db, profiles, all_candidates=False):
    """Target name -> list of emitted rules. Without a profile (or with
    ``all_candidates``) a target gets every candidate; that is the build
    `select` measures."""
    out = {}
    for name in sorted(targets.TARGETS):
        cands = candidates(db, targets.TARGETS[name])
        prof = profiles.get(name)
        if all_candidates or prof is None:
            out[name] = list(cands)
        else:
            sel = prof['rules']
            out[name] = [r for r in cands if
                         sel.get(r['id'], {}).get('selection') == 'emitted']
    return out


# ------------------------------------------------------------ patterns ---

class _Node:
    """A source pattern node with a stable identity across commuted forms:
    interior node k is always matched as $t<k>."""

    def __init__(self, op, w, name, args):
        self.op, self.w, self.name, self.args = op, w, name, args


def _annotate(src):
    interior = []

    def walk(e, root):
        if ir.is_var(e):
            return e
        if not ir.is_op(e):
            raise ValueError('constant in source pattern')
        if root:
            name = '$dst'
        else:
            name = '$t%d' % len(interior)
            interior.append(e[1])
        return _Node(e[0], e[1], name, [walk(a, False) for a in e[2:]])
    return walk(src, True), interior


def _forms(n):
    """All commuted forms of an annotated pattern. A comparison also has
    the form with the operands and the predicate exchanged."""
    if not isinstance(n, _Node):
        return [n]
    out = [[]]
    for a in n.args:
        out = [o + [f] for o in out for f in _forms(a)]
    res = []
    info, attr, _ = ops.parse(n.op)
    for args in out:
        res.append(_Node(n.op, n.w, n.name, args))
        if info.commutative:
            res.append(_Node(n.op, n.w, n.name,
                             [args[1], args[0]] + args[2:]))
        elif info.attr == 'pred' and ops.SWAPPED_PRED[attr] != attr:
            res.append(_Node(ops.make_key(info.name,
                                          ops.SWAPPED_PRED[attr]),
                             n.w, n.name, [args[1], args[0]]))
    return res


def _plain(n):
    if not isinstance(n, _Node):
        return n
    return (n.op, n.w) + tuple(_plain(a) for a in n.args)


_CPP_PRED = {p: 'CmpInst::ICMP_' + p.upper() for p in ops.PREDS}


def _lines(n, out, checks=None):
    """Appends the match patterns of ``n`` and of its operands to ``out``
    and the C++ conditions on their attributes to ``checks``."""
    if checks is None:
        checks = []
    operands = []
    for a in n.args:
        if isinstance(a, _Node):
            _lines(a, out, checks)
            operands.append(a.name)
        else:
            operands.append('$x%d' % a[1])
    info, attr, res = ops.parse(n.op)
    tag = n.name[1:]
    if info.results == 1:
        defs = [n.name]
    else:
        # The other results of the instruction are not part of the
        # pattern.
        defs = [n.name if k == res else '$%s_r%d' % (tag, k)
                for k in range(info.results)]
    if info.attr == 'pred':
        operands.insert(0, '$%s_p' % tag)
        checks.append('${%s_p}.getPredicate() == %s' % (tag,
                                                        _CPP_PRED[attr]))
    elif info.attr == 'imm':
        operands.append('$%s_i' % tag)
        checks.append('${%s_i}.getImm() == %d' % (tag, attr))
    out.append('(%s %s)' % (info.name, ', '.join(defs + operands)))
    return out


def rule_dnf(rule):
    return [tuple(precond.atom_from_json(a) for a in d['pred_json'])
            for d in rule['disjuncts']]


def variants(rule):
    """Match pattern lines of every distinct commuted form of the source.
    Two forms are the same rule if renaming the variables of one by first
    occurrence gives the same source, replacement and precondition; only the
    first is kept."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    dnf = rule_dnf(rule)
    root, _ = _annotate(src)
    out, seen = [], set()
    for form in _forms(root):
        e = _plain(form)
        order = ir.variables(e)
        # The variables that only a sibling reads keep their order.
        order += [v for v in range(len(rule['vw'])) if v not in order]
        m = {old: new for new, old in enumerate(order)}
        sig = (ir.rename(e, m),
               synth.normalize_commutative(ir.rename(tgt, m)),
               precond.canonical_dnf(
                   [[precond.rename_atom(a, m) for a in p] for p in dnf]))
        if sig in seen:
            continue
        seen.add(sig)
        checks = []
        pats = _lines(form, [], checks)
        if checks:
            pats.append('[{ return %s; }]' % ' && '.join(checks))
        out.append(pats)
    return out


def record_names(rule):
    return [rule['id'] if k == 0 else '%s_c%d' % (rule['id'], k)
            for k in range(len(variants(rule)))]


def _lit_imm(k):
    return {'0': '0', '1': '1', '-1': '-1'}[k]


def _needs_cpp_apply(tgt, const_vars=()):
    """True if the replacement has a node that an apply pattern cannot
    write: a constant that is not a literal, a computed constant, an
    operator with an attribute or an instruction with several results."""
    if ir.is_const(tgt):
        return True
    if not ir.is_op(tgt):
        return False
    if ir.is_constant_expr(tgt, const_vars):
        return True
    info = ops.parse(tgt[0])[0]
    return info.attr is not None or info.results != 1 or \
        any(_needs_cpp_apply(a, const_vars) for a in tgt[2:])


def _rule_needs_cpp_apply(rule):
    return bool(rule.get('region')) or \
        _needs_cpp_apply(ir.from_json(rule['replacement_json']),
                         tuple(rule.get('const_vars', ())))


def _region_outputs(rule):
    """(register of the old value, replacement, kind) of each output
    below the root of a rule with several outputs."""
    if not rule.get('region'):
        return []
    src = ir.from_json(rule['source_json'])
    kinds = _interior_kinds(src)
    return [('T%d' % (o['node'] - 1), ir.from_json(o['replacement_json']),
             kinds[o['node'] - 1]) for o in rule['region']['outputs'][1:]]


def _region_inputs(rule):
    """The variables that the replacements of a rule with several
    outputs read."""
    vs = set(ir.variables(ir.from_json(rule['replacement_json'])))
    for _, t, _ in _region_outputs(rule):
        vs |= set(ir.variables(t))
    return sorted(vs)


def _siblings(rule):
    """(sibling, its replacement or None, operand references) of each
    other root of a rule for a region with several roots
    (girs/sibling.py). None as the replacement: the sibling stays, and a
    replacement reads its results. A reference is the value of the region
    that an operand is: ('var', i), ('node', k) (the value below the root
    with the register T<k-1>) or ('sib', j) (the result of the sibling
    j)."""
    out = []
    for s in (rule.get('region') or {}).get('siblings') or ():
        b = ir.from_json(s['source_json'])
        refs = [('var', o['var']) if 'var' in o else
                ('node', o['node']) if 'node' in o else
                ('sib', o['sibling']) for o in s['operands']] \
            if 'operands' in s else [('var', x[1]) for x in b[2:]]
        out.append((b, None if s['stays'] else
                    ir.from_json(s['replacement_json']), tuple(refs)))
    return out


def _sibling_vars(rule):
    """The variables that only the siblings read: the pattern of the
    root does not have them, and the guard takes them from the operands
    of the siblings."""
    return list((rule.get('region') or {}).get('sibling_vars', ()))


def _pattern_vars(rule):
    sv = set(_sibling_vars(rule))
    return [i for i in range(len(rule['vw'])) if i not in sv]


def _sibling_results(b, vw):
    """(operand index, width or None) of the results of the instruction
    of the sibling ``b`` that the guard reads. None as the width: one
    bit, whatever the width map is (a carry or an overflow result)."""
    info, _, res = ops.parse(b[0])
    kinds = info.meta.get('result_kinds')
    if info.results == 1 or not kinds:
        return [(res, b[1])]
    main = ir.width(b[2], vw)
    return [(k, main if kind == 'main' else None)
            for k, kind in enumerate(kinds)]


def _ref_reg(ref, sibs):
    """The C++ name of the register of a value of the region."""
    if ref[0] == 'var':
        return 'X%d' % ref[1]
    if ref[0] == 'node':
        return 'T%d' % (ref[1] - 1)
    return 'S%dR%d' % (ref[1], ops.parse(sibs[ref[1]][0][0])[2])


def _reused(rule):
    """The values below the root that a replacement of a rule with
    several roots reads and does not build: {node: its register}. A node
    that occurs twice in the tree is two instructions."""
    if not _siblings(rule):
        return {}
    nodes = ir.interior_nodes(ir.from_json(rule['source_json']))
    return {n: 'T%d' % k for k, n in enumerate(nodes)
            if nodes.count(n) == 1}


def _replacements(rule):
    """The replacements of the roots that the rule replaces."""
    return [ir.from_json(rule['replacement_json'])] + \
        [t for _, t, _ in _region_outputs(rule)] + \
        [rb for _, rb, _ in _siblings(rule) if rb is not None]


def _built_nodes(rule):
    """The nodes of the replacements that the apply function builds: not
    the instructions that are there (a sibling that stays, a value below
    the root) and not the operands of those."""
    reuse = _reused(rule)
    there = {_instr_key(b) for b, rb, _ in _siblings(rule) if rb is None}
    out = []

    def walk(e):
        if not ir.is_op(e) or e in reuse or _instr_key(e) in there:
            return
        out.append(e)
        for x in e[2:]:
            walk(x)
    for t in _replacements(rule):
        walk(t)
    return out


def _plan_inputs(rule):
    """The registers that must be defined before the position of the
    replacement (planRegion): the ones that a new instruction or a
    sibling that stays reads, but not the results of the siblings that
    stay."""
    sibs = _siblings(rule)
    if not sibs:
        return ['X%d' % v for v in _region_inputs(rule)]
    reuse = _reused(rule)
    there = {_instr_key(b) for b, rb, _ in sibs if rb is None}
    regs = set()

    def walk(e):
        if ir.is_var(e):
            regs.add('X%d' % e[1])
        elif ir.is_op(e) and e in reuse:
            regs.add(reuse[e])
        elif ir.is_op(e) and _instr_key(e) not in there:
            for x in e[2:]:
                walk(x)
    for t in _replacements(rule):
        walk(t)
    for b, rb, refs in sibs:
        if rb is None:
            regs |= {_ref_reg(r, sibs) for r in refs if r[0] != 'sib'}
    return sorted(regs, key=lambda x: (x[0] != 'X', int(x[1:])))


def _cpp_find_siblings(rule):
    """The lines of the guard that find the other roots of a rule for a
    region with several roots and that fill Plan.Sibs and Plan.Extra.
    Each sibling is an instruction of the block of the root that reads a
    value that the tree or an earlier sibling has, and that has the
    operator and the operands of the rule. An operand that is a variable
    of the siblings only gets its register here."""
    sibs = _siblings(rule)
    svars = _sibling_vars(rule)
    _, interior = _annotate(ir.from_json(rule['source_json']))
    out = ['  // The other roots of the region.',
           '  MachineInstr *Root = MRI.getVRegDef(Dst);',
           '  if (!Root)', '    return false;',
           '  Plan = RegionPlan();'] + [
        '  Register X%d;' % v for v in svars]
    bound = set()
    for j, (b, _, refs) in enumerate(sibs):
        info, attr, res = ops.parse(b[0])
        forms = [(attr, refs)]
        if info.commutative:
            forms.append((attr, (refs[1], refs[0]) + refs[2:]))
        elif info.attr == 'pred' and ops.SWAPPED_PRED[attr] != attr:
            forms.append((ops.SWAPPED_PRED[attr], (refs[1], refs[0])))
        fresh = {r[1] for r in refs
                 if r[0] == 'var' and r[1] in svars and r[1] not in bound}
        anchor = [r for r in refs if not (r[0] == 'var' and r[1] in fresh)][0]
        conds = ['MI.getOpcode() != TargetOpcode::%s' % info.name]
        if info.shape == 'unmerge':
            conds.append('MI.getNumExplicitDefs() <= %d' % res)
            first = 'MI.getNumOperands() - 1'
        else:
            first = '%d' % (info.results + (info.attr == 'pred'))
        if info.attr == 'imm':
            conds.append('MI.getOperand(%s + %d).getImm() != %d' % (
                first, len(b) - 2, attr))
        body = ['        if (%s)' % ' ||\n            '.join(conds),
                '          return false;']
        for a, rs in dict.fromkeys(forms):
            c = ['MI.getOperand(1).getPredicate() == %s' % _CPP_PRED[a]] \
                if info.attr == 'pred' else []
            got = {}
            for k, r in enumerate(rs):
                opnd = 'MI.getOperand(%s%s).getReg()' % (
                    first, ' + %d' % k if k else '')
                if r[0] == 'var' and r[1] in fresh:
                    if r[1] in got:
                        c.append('%s == %s' % (opnd, got[r[1]]))
                    else:
                        got[r[1]] = opnd
                else:
                    c.append('%s == %s' % (opnd, _ref_reg(r, sibs)))
            if got:
                body += ['        if (%s) {' % ' &&\n            '.join(c)] + [
                    '          X%d = %s;' % (v, o)
                    for v, o in sorted(got.items())
                ] + ['          return true;', '        }']
            else:
                body += ['        if (%s)' % ' &&\n            '.join(c),
                         '          return true;']
        out += ['  // %s' % ir.to_sexpr(b),
                '  MachineInstr *Sib%d = findSiblingRoot(' % j,
                '      MRI, *Root, %s,' % _ref_reg(anchor, sibs),
                '      [&](const MachineInstr &MI) {'] + body + [
            '        return false;', '      },',
            '      /*MaxUsers=*/8, {%s}, Plan.Sibs);' % ', '.join(
                'T%d' % k for k in range(len(interior))),
            '  if (!Sib%d)' % j, '    return false;',
            '  Plan.Sibs.push_back(Sib%d);' % j] + [
            '  [[maybe_unused]] Register S%dR%d = '
            'Sib%d->getOperand(%d).getReg();' % (j, k, j, k)
            for k, _ in _sibling_results(b, rule['vw'])]
        bound |= fresh
    if svars:
        out.append('  Plan.Extra = {%s};' % ', '.join(
            'X%d' % v for v in svars))
    # The values below the root that the rule needs to remove have no
    # user outside the region: the tree, and the siblings that the rule
    # replaces.
    dead = rule['region'].get('dead_nodes')
    if dead is None:
        dead = list(range(1, len(interior) + 1)) \
            if rule['needs_one_use'] else []
    for k in dead:
        users = 1 + sum(r == ('node', k) for _, rb, refs in sibs
                        if rb is not None for r in refs)
        out += ['  if (!hasNUses(MRI, T%d, %d))' % (k - 1, users),
                '    return false;']
    return out


def _instr_key(e):
    """The instruction of a replacement node: the results of one
    instruction with several results are one instruction."""
    info, attr, _ = ops.parse(e[0])
    return (info.name, attr, e[1] if info.results == 1 else None) + e[2:]


_CPP_APINT = {'G_ADD': '(%s + %s)', 'G_SUB': '(%s - %s)',
              'G_MUL': '(%s * %s)', 'G_AND': '(%s & %s)',
              'G_OR': '(%s | %s)', 'G_XOR': '(%s ^ %s)',
              'G_SHL': '%s.shl(%s)', 'G_LSHR': '%s.lshr(%s)',
              'G_ASHR': '%s.ashr(%s)',
              'G_SMIN': 'APIntOps::smin(%s, %s)',
              'G_SMAX': 'APIntOps::smax(%s, %s)',
              'G_UMIN': 'APIntOps::umin(%s, %s)',
              'G_UMAX': 'APIntOps::umax(%s, %s)',
              'G_UADDSAT': '%s.uadd_sat(%s)',
              'G_SADDSAT': '%s.sadd_sat(%s)',
              'G_USUBSAT': '%s.usub_sat(%s)',
              'G_SSUBSAT': '%s.ssub_sat(%s)'}
assert set(_CPP_APINT) == set(ir.RECIPE_OPS)


def _cpp_const(e, bits):
    """The C++ APInt expression of the constant expression ``e``.
    ``bits(w)`` is the C++ expression of the width ``w``. The constant
    variable i is the APInt C<i>."""
    if ir.is_var(e):
        return 'C%d' % e[1]
    if ir.is_lit(e):
        return {'0': 'APInt::getZero(%s)', '1': 'APInt(%s, 1)',
                '-1': 'APInt::getAllOnes(%s)'}[e[2]] % bits(e[1])
    if not ir.is_op(e):
        return 'APInt(%s, UINT64_C(%d))' % (bits(e[1]), e[2])
    if e[0] == 'G_ZEXT':
        return '%s.zext(%s)' % (_cpp_const(e[2], bits), bits(e[1]))
    return _CPP_APINT[e[0]] % tuple(_cpp_const(a, bits) for a in e[2:])


def _cpp_recipe_checks(tgt, const_vars, bits):
    """The C++ conditions of smt.Encoder.recipe_guard, in the same order:
    each shift of a computed constant has an amount smaller than its
    width, and so has each shift whose amount is a computed constant."""
    out = []
    for c in ir.computed_constants(tgt, const_vars):
        for n in ir.nodes(c):
            if n[0] in ir.SHIFT_OPS:
                out.append('%s.ult(%s)' % (_cpp_const(n[3], bits),
                                           bits(n[1])))
    for w, c in ir.computed_amounts(tgt, const_vars):
        out.append('%s.ult(%s)' % (_cpp_const(c, bits), bits(w)))
    return out


def _bits_fn(rule):
    types = _type_sources(rule)

    def bits(w):
        return 'MRI.getType(%s).getScalarSizeInBits()' % _type_source(
            types, w)
    return bits


_KIND_NAME = {'f': 'floating-point', 'i': 'integer'}


def _type_source(types, w, kind=None, fmt='%s'):
    """The first register of ``types`` (see _type_sources) that has the
    width ``w`` and the kind ``kind`` ('f', 'i' or None: any). A register
    of an unknown kind can give the type of an integer, not the type of a
    floating-point value."""
    for tw, tk, reg in types:
        if tw == w and (kind is None or tk == kind or
                        (kind == 'i' and tk is None)):
            return fmt % reg
    if kind is None:
        raise ValueError('no operand with width %d' % w)
    raise ValueError('no %s operand with width %d' % (_KIND_NAME[kind], w))


def _check_kinds(src, tgt):
    """Raises ValueError if the types of the rule cannot be written: a
    value that is an integer and a floating-point value, or a
    floating-point constant (the patterns match and build G_CONSTANT)."""
    root_kind = ir.result_kind(src)
    kinds = ir.var_kinds(tgt, root_kind, ir.var_kinds(src))
    if 'x' in kinds.values():
        raise ValueError('a value is used as an integer and as a '
                         'floating-point value')
    return root_kind, kinds


def _apply_patterns(tgt, vw, root_w, src=None):
    """MIR apply patterns building ``tgt`` into $dst. ``src`` is the
    source pattern; it gives the kinds of the values."""
    root_kind, kinds = _check_kinds(src, tgt) if src is not None else \
        (None, {})
    if ir.is_var(tgt):
        return ['(GIReplaceReg $dst, $x%d)' % tgt[1]]
    if ir.is_lit(tgt):
        if root_kind == 'f':
            raise ValueError('a floating-point constant in the replacement')
        return ['(G_CONSTANT $dst, (GITypeOf<"$dst"> %s))' %
                _lit_imm(tgt[2])]
    pats = []
    n = [0]
    types = [(root_w, root_kind, 'dst')] + \
        [(w, kinds.get(i), 'x%d' % i) for i, w in enumerate(vw)]

    def type_of(w, kind):
        return _type_source(types, w, kind, 'GITypeOf<"$%s">')

    def walk(e, dst, kind):
        ops = []
        for k, a in enumerate(e[2:]):
            ak = ir.operand_kind(e, k, kind)
            if ir.is_var(a):
                ops.append('$x%d' % a[1])
            elif ir.is_lit(a):
                if ak == 'f':
                    raise ValueError('a floating-point constant in the '
                                     'replacement')
                ops.append('(%s %s)' % (type_of(a[1], ak), _lit_imm(a[2])))
            else:
                t = '$n%d' % n[0]
                n[0] += 1
                ak = ir.result_kind(a, ak)
                walk(a, '%s:%s' % (type_of(a[1], ak), t), ak)
                ops.append(t)
        pats.append('(%s %s, %s)' % (e[0], dst, ', '.join(ops)))

    walk(tgt, '$dst', ir.result_kind(tgt, root_kind))
    return pats


def _interior_kinds(src):
    """The kinds of the interior values of the source, in the order of
    _annotate."""
    out = []

    def walk(e, kind, root):
        if not ir.is_op(e):
            return
        kind = ir.result_kind(e, kind)
        if not root:
            out.append(kind)
        for k, a in enumerate(e[2:]):
            walk(a, ir.operand_kind(e, k, kind), False)
    walk(src, None, True)
    return out


def _type_sources(rule):
    """(width, kind, C++ expression of a register) of the values that a
    new value can take its type from: the root, the variables and the
    interior values of the source."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    _, interior = _annotate(src)
    root_kind, kinds = _check_kinds(src, tgt)
    # The result of a sibling with one result has a width of the rule.
    sibs = [(b[1], ir.result_kind(b), 'S%dR%d' % (j, ops.parse(b[0])[2]))
            for j, (b, _, _) in enumerate(_siblings(rule))
            if ops.parse(b[0])[0].results == 1]
    return [(src[1], root_kind, 'Dst')] + \
        [(w, kinds.get(i), 'X%d' % i) for i, w in enumerate(rule['vw'])] + \
        [(w, k, 'T%d' % n)
         for n, (w, k) in enumerate(zip(interior, _interior_kinds(src)))] + \
        sibs


def _apply_params(rule):
    """The registers that the pattern of the rule gives to the guard and
    to the apply function."""
    _, interior = _annotate(ir.from_json(rule['source_json']))
    return ['Dst'] + ['X%d' % i for i in _pattern_vars(rule)] + \
        ['T%d' % k for k in range(len(interior))]


def _cpp_apply(rule):
    """The C++ function that builds the replacement before the root
    instruction and erases the root."""
    tgt = ir.from_json(rule['replacement_json'])
    cv = tuple(rule.get('const_vars', ()))
    types = _type_sources(rule)
    bits = _bits_fn(rule)
    # The guard checked that these are constants.
    body = ['  APInt C%d = *getIConstantVRegVal(X%d, MRI);' % (i, i)
            for i in cv]
    built = {}   # (instruction, operands) -> variable
    n = [0]

    src = ir.from_json(rule['source_json'])
    root_kind = ir.result_kind(src)

    def ty(w, kind=None):
        return _type_source(types, w, kind, 'MRI.getType(%s)')

    def no_fp_constant(kind):
        if kind == 'f':
            raise ValueError('a floating-point constant in the replacement')

    def new(text):
        name = 'N%d' % n[0]
        n[0] += 1
        body.append('  [[maybe_unused]] auto %s = %s;' % (name, text))
        return name

    outs = _region_outputs(rule)
    sibs = _siblings(rule)
    # The values below the root that are there: a replacement reads them.
    reuse = _reused(rule)
    for j, (b, rb, _) in enumerate(sibs):
        if rb is None:
            # The instruction of the sibling is there: a node of a
            # replacement that is that instruction reads its results.
            built[_instr_key(b)] = 'NSib%d' % j
        else:
            outs = outs + [('S%dR%d' % (j, ops.parse(b[0])[2]), rb,
                            ir.result_kind(b))]
    # (instruction, result) -> the register that the instruction defines:
    # the root and the old values of the other outputs.
    want = {}
    for dname, t in [('Dst', tgt)] + [(d, t) for d, t, _ in outs]:
        if ir.is_op(t) and not ir.is_constant_expr(t, cv) and \
                t not in reuse and _instr_key(t) not in built:
            want.setdefault((_instr_key(t), ops.parse(t[0])[2]), dname)

    def walk(e, dst=None, kind=None):
        """Returns the C++ expression of the value of ``e``, which its
        user needs with the kind ``kind``."""
        if ir.is_var(e):
            return 'X%d' % e[1]
        if not ir.is_op(e):
            # The constant has the width of the type at the width map of
            # the match: a literal is 0, 1 or -1 at every width, and
            # another constant is its value modulo that width, as in the
            # proof.
            no_fp_constant(kind)
            t = ty(e[1], kind)
            size = '%s.getScalarSizeInBits()' % t
            if ir.is_lit(e):
                val = {'0': 'APInt::getZero(%s)', '1': 'APInt(%s, 1)',
                       '-1': 'APInt::getAllOnes(%s)'}[e[2]] % size
            else:
                val = ('APInt(%s, UINT64_C(%d), /*isSigned=*/false, '
                       '/*implicitTrunc=*/true)' % (size, ir.leaf_value(e)))
            return new('B.buildConstant(%s, %s)' % (t, val)) + '.getReg(0)'
        if ir.is_constant_expr(e, cv):
            # A computed constant.
            no_fp_constant(kind)
            if e not in built:
                built[e] = new('B.buildConstant(%s, %s)' % (
                    dst or ty(e[1], kind), _cpp_const(e, bits)))
            return '%s.getReg(0)' % built[e]
        if e in reuse:
            return reuse[e]
        info, attr, res = ops.parse(e[0])
        kind = ir.result_kind(e, kind)
        key = _instr_key(e)
        if key not in built:
            args = [walk(a, None, ir.operand_kind(e, k, kind))
                    for k, a in enumerate(e[2:])]
            # Each result of the instruction gets its type from the
            # operator: the main type or s1.
            if info.results == 1:
                rtys = [want.get((key, 0)) or ty(e[1], kind)]
            else:
                kinds = info.meta['result_kinds']
                mainw = ir.width(e[2], rule['vw'])
                rtys = [want.get((key, n)) or
                        (ty(mainw, 'i') if k == 'main' else ty(1, 'i'))
                        for n, k in enumerate(kinds)]
            if info.attr == 'pred':
                text = 'B.buildICmp(%s, %s, %s)' % (
                    _CPP_PRED[attr], rtys[0], ', '.join(args))
            else:
                srcs = list(args)
                if info.attr == 'imm':
                    srcs.append('int64_t(%d)' % attr)
                text = 'B.buildInstr(TargetOpcode::%s, {%s}, {%s})' % (
                    info.name, ', '.join(rtys), ', '.join(srcs))
            built[key] = new(text)
        return '%s.getReg(%d)' % (built[key], res)

    def is_def(dname, t):
        """True if a new instruction defines the register ``dname``."""
        return ir.is_op(t) and not ir.is_constant_expr(t, cv) and \
            want.get((_instr_key(t), ops.parse(t[0])[2])) == dname

    region_rule = bool(outs or sibs)
    if not region_rule:
        walk(tgt, 'Dst', root_kind)
    params = ['MachineIRBuilder &B', 'MachineInstr &Root'] + \
        (['const RegionPlan &Plan'] if region_rule else []) + \
        ['Register %s' % p for p in _apply_params(rule)]
    head = ['  B.setInstrAndDebugLoc(Root);']
    tail = []
    if region_rule:
        # The replacement of an output that is not the result of a new
        # instruction of its own is a copy.
        for dname, t, kind in [('Dst', tgt, root_kind)] + outs:
            v = walk(t, None, kind)
            if not is_def(dname, t):
                body.append('  B.buildCopy(%s, %s);' % (dname, v))
    if sibs:
        # The match step found the siblings and the position
        # (planRegion). A sibling that stays and that is after the
        # position is moved before it.
        head = ['  B.setInstrAndDebugLoc(applyRegionPlan(Plan));'] + [
            '  [[maybe_unused]] Register X%d = Plan.Extra[%d];' % (v, i)
            for i, v in enumerate(_sibling_vars(rule))]
        for j, (b, rb, _) in enumerate(sibs):
            head.append('  MachineInstr *Sib%d = Plan.Sibs[%d];' % (j, j))
            head += ['  [[maybe_unused]] Register S%dR%d = '
                     'Sib%d->getOperand(%d).getReg();' % (j, k, j, k)
                     for k, _ in _sibling_results(b, rule['vw'])]
            if rb is None:
                head.append('  [[maybe_unused]] MachineInstrBuilder '
                            'NSib%d(B.getMF(), Sib%d);' % (j, j))
            else:
                # A new instruction defines the registers of this
                # sibling. The sibling releases them first, so that a
                # register never has two definitions (the builder reads
                # the definition of an operand when it folds constants).
                head.append('  releaseResults(MRI, *Sib%d);' % j)
                tail.append('  Sib%d->eraseFromParent();' % j)
        head.append('  releaseResults(MRI, Root);')
    elif outs:
        # The old instructions are found before a new instruction defines
        # their registers, and the replacement is built before the first
        # of them (isJointRegion): it then dominates the users of every
        # output.
        head = ['  MachineInstr *Old%d = MRI.getVRegDef(%s);' % (n, d)
                for n, (d, _, _) in enumerate(outs)] + [
            '  B.setInstrAndDebugLoc(applyRegionPlan(Plan));'] + [
            '  releaseResults(MRI, *Old%d);' % n
            for n in range(len(outs))] + ['  releaseResults(MRI, Root);']
        tail = ['  Old%d->eraseFromParent();' % n for n in range(len(outs))]
    out = ['/// Builds %s.' % rule['replacement'],
           'inline void %s(%s) {' % (_apply_name(rule), ', '.join(params)),
           '  [[maybe_unused]] MachineRegisterInfo &MRI = *B.getMRI();'] + \
        head + body + tail + ['  Root.eraseFromParent();', '}']
    return '\n'.join(out)


def why_not_emittable(rule):
    """None if the emitter can write the rule, else the reason."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    cv = tuple(rule.get('const_vars', ()))
    if ops.parse(src[0])[0].results != 1:
        return 'the root instruction has several results'
    for n in [src] + ir.interior_nodes(src):
        info = ops.parse(n[0])[0]
        if info.shape not in ops._EMIT_SHAPES:
            return 'no match pattern for the shape %s' % info.shape
    # The guard reads a constant of the source with getIConstantVRegVal.
    src_kinds = ir.var_kinds(src)
    if any(src_kinds.get(v) == 'f' for v in cv):
        return 'a floating-point constant in the source'
    sibs = _siblings(rule)
    for j, (b, rb, refs) in enumerate(sibs):
        info = ops.parse(b[0])[0]
        if info.shape not in ops._EMIT_SHAPES + ('unmerge',):
            return 'no match of another root with the shape %s' % info.shape
        if rb is None and info.meta.get('may_trap'):
            return 'another root that can trap is not moved'
        if rb is not None and info.results != 1:
            return 'another root with several results is not replaced'
        if rb is None and any(r[0] == 'sib' and sibs[r[1]][1] is not None
                              for r in refs):
            return 'a root that stays reads a root that is replaced'
    for n in _built_nodes(rule):
        why = ops.capability(ops.parse(n[0])[0], 'emit')
        if why != 'yes':
            return '%s: %s' % (n[0], why)
    try:
        _annotate(src)
        _cpp_recipe_checks(tgt, cv, _bits_fn(rule))
        if _rule_needs_cpp_apply(rule):
            _cpp_apply(rule)
        else:
            _apply_patterns(tgt, rule['vw'], rule['source_json']['w'], src)
    except ValueError as e:
        return str(e)
    return None


def emittable(rule):
    return why_not_emittable(rule) is None


def _guard_name(rule):
    return 'guard_' + rule['id']


def _apply_name(rule):
    # A rule and its one-use variant have the same replacement.
    return 'apply_' + rule.get('variant_of', rule['id'])


