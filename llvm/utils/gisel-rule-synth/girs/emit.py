def emit(db, profiles=None, all_candidates=False):
    """Returns (td text, inc text, info)."""
    sel = selection(db, profiles or {}, all_candidates)
    sel = {t: [r for r in rs if emittable(r)] for t, rs in sel.items()}
    ids = {r['id'] for rs in sel.values() for r in rs}
    rules = [r for r in candidates(db) if r['id'] in ids]
    td, names = emit_td(rules, sel)
    inc = emit_inc(rules, sel, names)
    info = {'rules': len(rules),
            'records': sum(len(n) for n in names.values()),
            'forms_before_dedup': sum(
                len(ir.commuted_variants(ir.from_json(r['source_json'])))
                for r in rules),
            'targets': {t: {'rules': len(rs),
                            'records': sum(len(names[r['id']]) for r in rs)}
                        for t, rs in sel.items()}}
    return td, inc, info
