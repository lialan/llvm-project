"""TableGen / C++ emission from the verified rule library.

Which rules are emitted is decided per target by the target profiles
(targets/<Target>.json, written by `gi-rule-synth.py select`). The rule
records and guards are target independent and are emitted once, for the
union of all targets; each target gets its own GICombineGroup and its own
list of record names. For each emitted rule the emitter writes

* one GICombineRule per *distinct* commuted form of the source pattern (the
  GlobalISel combiner does not try commuted operands on its own). A commuted
  form that is the same rule after renaming its variables is not emitted;
* one inline C++ guard that checks the widths of all pattern nodes against
  the verified width schedules and evaluates the synthesized known-bits
  precondition, a disjunction of conjunctions, with GISelValueTracking. The
  disjuncts are tried in order of corpus coverage and known bits are only
  queried when a disjunct needs them.

Nothing here runs a solver: emission is a pure function of the library and
the profiles, so `gi-rule-synth.py emit --check` can detect stale generated
files.
"""

