# ---------------------------------------------------------- selection ---

ONE_USE_SUFFIX = '_1u'


def widened_bits(rule):
    """See synth.widened_width."""
    return synth.widened_width(ir.from_json(rule['source_json']),
                               ir.from_json(rule['replacement_json']))


def one_use_variant(rule):
    """The variant of ``rule`` that applies only if no interior value of
    the source has another user, or None if the rule has that guard or does
    not need it.

    A rule removes the interior operations of its source only if they have
    no other user. If the replacement costs as much as the root alone, the
    rule removes nothing from a source with a shared interior value: it
    only changes the code, and the changed code can be worse for the
    target. `select` measures the two variants and keeps one of them."""
    if rule['needs_one_use'] or rule['cost']['replacement'] == 0 or \
            rule.get('region') or \
            not ir.interior_nodes(ir.from_json(rule['source_json'])):
        return None
    v = dict(rule)
    v['id'] = rule['id'] + ONE_USE_SUFFIX
    v['needs_one_use'] = True
    v['variant_of'] = rule['id']
    return v


def candidates(db, target=None):
    """Rules a target may select (any target if ``target`` is None): proved,
    cheaper than their source under the generic cost model, and not
    dominated by a rule with the same source. A rule that moves an operation
    to a wider type is a candidate only if that type is not wider than the
    registers of the target (Target.native_bits). Each rule is followed by
    its one-use variant, if it has one. The rules are ordered as the
    combiner tries them: the rule that removes the most first, then the
    smaller source pattern."""
    bits = target.native_bits if target else targets.NATIVE_BITS
    out = [r for r in db['rules']
           if r['semantic_status']['kind'] == 'verified_refinement' and
           (r['class'] == 'reduces_cost' or
            (r['class'] == 'widens_operation' and
             r['cost']['replacement'] < r['cost']['source'] and
             widened_bits(r) <= bits)) and
           r['disjuncts'] and 'dominated_by' not in r]
    # A rule with several outputs applies only if a value below the root
    # has another user; it comes before the rule of the root alone.
    out.sort(key=lambda r: (not r.get('region'),
                            r['cost']['replacement'] - r['cost']['source'],
                            r['cost']['source'], r['id']))
    res = []
    for r in out:
        res.append(r)
        v = one_use_variant(r)
        if v:
            res.append(v)
    return res


def load_profiles(profile_dir=None):
    """Target name -> profile, for every profile file that exists."""
    out = {}
    for name, t in sorted(targets.TARGETS.items()):
        path = os.path.join(profile_dir, name + '.json') if profile_dir \
            else t.profile_path
        if os.path.exists(path):
            with open(path) as f:
                out[name] = json.load(f)
    return out


def selection(db, profiles, all_candidates=False):
    """Target name -> list of emitted rules. Without a profile (or with
    ``all_candidates``) a target gets every candidate; that is the build
    `select` measures."""
    out = {}
    for name in sorted(targets.TARGETS):
        cands = candidates(db, targets.TARGETS[name])
        prof = profiles.get(name)
        if all_candidates or prof is None:
            out[name] = list(cands)
        else:
            sel = prof['rules']
            out[name] = [r for r in cands if
                         sel.get(r['id'], {}).get('selection') == 'emitted']
    return out


# ------------------------------------------------------------ patterns ---

class _Node:
    """A source pattern node with a stable identity across commuted forms:
    interior node k is always matched as $t<k>."""

    def __init__(self, op, w, name, args):
        self.op, self.w, self.name, self.args = op, w, name, args


def _annotate(src):
    interior = []

    def walk(e, root):
        if ir.is_var(e):
            return e
        if not ir.is_op(e):
            raise ValueError('constant in source pattern')
        if root:
            name = '$dst'
        else:
            name = '$t%d' % len(interior)
            interior.append(e[1])
        return _Node(e[0], e[1], name, [walk(a, False) for a in e[2:]])
    return walk(src, True), interior


def _forms(n):
    """All commuted forms of an annotated pattern. A comparison also has
    the form with the operands and the predicate exchanged."""
    if not isinstance(n, _Node):
        return [n]
    out = [[]]
    for a in n.args:
        out = [o + [f] for o in out for f in _forms(a)]
    res = []
    info, attr, _ = ops.parse(n.op)
    for args in out:
        res.append(_Node(n.op, n.w, n.name, args))
        if info.commutative:
            res.append(_Node(n.op, n.w, n.name,
                             [args[1], args[0]] + args[2:]))
        elif info.attr == 'pred' and ops.SWAPPED_PRED[attr] != attr:
            res.append(_Node(ops.make_key(info.name,
                                          ops.SWAPPED_PRED[attr]),
                             n.w, n.name, [args[1], args[0]]))
    return res


def _plain(n):
    if not isinstance(n, _Node):
        return n
    return (n.op, n.w) + tuple(_plain(a) for a in n.args)


_CPP_PRED = {p: 'CmpInst::ICMP_' + p.upper() for p in ops.PREDS}


def _lines(n, out, checks=None):
    """Appends the match patterns of ``n`` and of its operands to ``out``
    and the C++ conditions on their attributes to ``checks``."""
    if checks is None:
        checks = []
    operands = []
    for a in n.args:
        if isinstance(a, _Node):
            _lines(a, out, checks)
            operands.append(a.name)
        else:
            operands.append('$x%d' % a[1])
    info, attr, res = ops.parse(n.op)
    tag = n.name[1:]
    if info.results == 1:
        defs = [n.name]
    else:
        # The other results of the instruction are not part of the
        # pattern.
        defs = [n.name if k == res else '$%s_r%d' % (tag, k)
                for k in range(info.results)]
    if info.attr == 'pred':
        operands.insert(0, '$%s_p' % tag)
        checks.append('${%s_p}.getPredicate() == %s' % (tag,
                                                        _CPP_PRED[attr]))
    elif info.attr == 'imm':
        operands.append('$%s_i' % tag)
        checks.append('${%s_i}.getImm() == %d' % (tag, attr))
    out.append('(%s %s)' % (info.name, ', '.join(defs + operands)))
    return out


def rule_dnf(rule):
    return [tuple(precond.atom_from_json(a) for a in d['pred_json'])
            for d in rule['disjuncts']]


def variants(rule):
    """Match pattern lines of every distinct commuted form of the source.
    Two forms are the same rule if renaming the variables of one by first
    occurrence gives the same source, replacement and precondition; only the
    first is kept."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    dnf = rule_dnf(rule)
    root, _ = _annotate(src)
    out, seen = [], set()
    for form in _forms(root):
        e = _plain(form)
        order = ir.variables(e)
        m = {old: new for new, old in enumerate(order)}
        sig = (ir.rename(e, m),
               synth.normalize_commutative(ir.rename(tgt, m)),
               precond.canonical_dnf(
                   [[precond.rename_atom(a, m) for a in p] for p in dnf]))
        if sig in seen:
            continue
        seen.add(sig)
        checks = []
        pats = _lines(form, [], checks)
        if checks:
            pats.append('[{ return %s; }]' % ' && '.join(checks))
        out.append(pats)
    return out


def record_names(rule):
    return [rule['id'] if k == 0 else '%s_c%d' % (rule['id'], k)
            for k in range(len(variants(rule)))]


def _lit_imm(k):
    return {'0': '0', '1': '1', '-1': '-1'}[k]


def _needs_cpp_apply(tgt, const_vars=()):
    """True if the replacement has a node that an apply pattern cannot
    write: a constant that is not a literal, a computed constant, an
    operator with an attribute or an instruction with several results."""
    if ir.is_const(tgt):
        return True
    if not ir.is_op(tgt):
        return False
    if ir.is_constant_expr(tgt, const_vars):
        return True
    info = ops.parse(tgt[0])[0]
    return info.attr is not None or info.results != 1 or \
        any(_needs_cpp_apply(a, const_vars) for a in tgt[2:])


def _rule_needs_cpp_apply(rule):
    return bool(rule.get('region')) or \
        _needs_cpp_apply(ir.from_json(rule['replacement_json']),
                         tuple(rule.get('const_vars', ())))


def _region_outputs(rule):
    """(register of the old value, replacement, kind) of each output
    below the root of a rule with several outputs."""
    if not rule.get('region'):
        return []
    src = ir.from_json(rule['source_json'])
    kinds = _interior_kinds(src)
    return [('T%d' % (o['node'] - 1), ir.from_json(o['replacement_json']),
             kinds[o['node'] - 1]) for o in rule['region']['outputs'][1:]]


def _region_inputs(rule):
    """The variables that the replacements of a rule with several
    outputs read."""
    vs = set(ir.variables(ir.from_json(rule['replacement_json'])))
    for _, t, _ in _region_outputs(rule):
        vs |= set(ir.variables(t))
    sib = _sibling(rule)
    if sib is not None and sib[1] is not None:
        vs |= set(ir.variables(sib[1]))
    return sorted(vs)


def _sibling(rule):
    """(sibling, its replacement or None) of a rule for a region with two
    roots (girs/sibling.py), or None. None as the replacement: the
    sibling stays, and the replacement of the root reads its results."""
    sibs = (rule.get('region') or {}).get('siblings')
    if not sibs:
        return None
    s = sibs[0]
    return (ir.from_json(s['source_json']),
            None if s['stays'] else ir.from_json(s['replacement_json']))


def _sibling_results(b, vw):
    """(operand index, width or None) of the results of the instruction
    of the sibling ``b`` that the guard reads. None as the width: one
    bit, whatever the width map is (a carry or an overflow result)."""
    info, _, res = ops.parse(b[0])
    kinds = info.meta.get('result_kinds')
    if info.results == 1 or not kinds:
        return [(res, b[1])]
    main = ir.width(b[2], vw)
    return [(k, main if kind == 'main' else None)
            for k, kind in enumerate(kinds)]


def _sibling_name(rule):
    return 'sibling_' + rule.get('variant_of', rule['id'])


def _cpp_sibling(rule):
    """The C++ function that finds the sibling of a rule for a region
    with two roots: an instruction of the block of the root that reads
    the first operand of the sibling and that has its operator and its
    operands."""
    b = _sibling(rule)[0]
    info, attr, res = ops.parse(b[0])
    _, interior = _annotate(ir.from_json(rule['source_json']))
    forms = [(attr, b[2:])]
    if info.commutative:
        forms.append((attr, (b[3], b[2]) + b[4:]))
    elif info.attr == 'pred' and ops.SWAPPED_PRED[attr] != attr:
        forms.append((ops.SWAPPED_PRED[attr], (b[3], b[2])))
    conds = ['MI.getOpcode() == TargetOpcode::%s' % info.name]
    if info.shape == 'unmerge':
        conds.append('MI.getNumExplicitDefs() > %d' % res)
        first = 'MI.getNumOperands() - 1'
    else:
        first = '%d' % (info.results + (info.attr == 'pred'))
    if info.attr == 'imm':
        conds.append('MI.getOperand(%s + %d).getImm() == %d' % (
            first, len(b) - 2, attr))
    if interior:
        conds.append('!is_contained({%s}, MI.getOperand(0).getReg())' %
                     ', '.join('T%d' % k for k in range(len(interior))))
    alts = []
    for a, args in dict.fromkeys(forms):
        c = ['MI.getOperand(1).getPredicate() == %s' % _CPP_PRED[a]] \
            if info.attr == 'pred' else []
        c += ['MI.getOperand(%s%s).getReg() == X%d' % (
            first, ' + %d' % k if k else '', x[1])
            for k, x in enumerate(args)]
        alts.append(' && '.join(c))
    conds.append(alts[0] if len(alts) == 1 else
                 '(%s)' % ' ||\n            '.join('(%s)' % x for x in alts))
    params = ['const MachineRegisterInfo &MRI', 'MachineInstr &Root'] + \
        ['[[maybe_unused]] Register %s' % p for p in _apply_params(rule)[1:]]
    return '\n'.join([
        '/// The second root of %s: %s.' % (rule['id'], ir.to_sexpr(b)),
        'inline MachineInstr *%s(%s) {' % (_sibling_name(rule),
                                           ', '.join(params)),
        '  return findSiblingRoot(MRI, Root, X%d, [&](const MachineInstr '
        '&MI) {' % b[2][1],
        '    return %s;' % ' &&\n           '.join(conds),
        '  });', '}'])


def _instr_key(e):
    """The instruction of a replacement node: the results of one
    instruction with several results are one instruction."""
    info, attr, _ = ops.parse(e[0])
    return (info.name, attr, e[1] if info.results == 1 else None) + e[2:]


_CPP_APINT = {'G_ADD': '(%s + %s)', 'G_SUB': '(%s - %s)',
              'G_MUL': '(%s * %s)', 'G_AND': '(%s & %s)',
              'G_OR': '(%s | %s)', 'G_XOR': '(%s ^ %s)',
              'G_SHL': '%s.shl(%s)', 'G_LSHR': '%s.lshr(%s)',
              'G_ASHR': '%s.ashr(%s)',
              'G_SMIN': 'APIntOps::smin(%s, %s)',
              'G_SMAX': 'APIntOps::smax(%s, %s)',
              'G_UMIN': 'APIntOps::umin(%s, %s)',
              'G_UMAX': 'APIntOps::umax(%s, %s)',
              'G_UADDSAT': '%s.uadd_sat(%s)',
              'G_SADDSAT': '%s.sadd_sat(%s)',
              'G_USUBSAT': '%s.usub_sat(%s)',
              'G_SSUBSAT': '%s.ssub_sat(%s)'}
assert set(_CPP_APINT) == set(ir.RECIPE_OPS)


def _cpp_const(e, bits):
    """The C++ APInt expression of the constant expression ``e``.
    ``bits(w)`` is the C++ expression of the width ``w``. The constant
    variable i is the APInt C<i>."""
    if ir.is_var(e):
        return 'C%d' % e[1]
    if ir.is_lit(e):
        return {'0': 'APInt::getZero(%s)', '1': 'APInt(%s, 1)',
                '-1': 'APInt::getAllOnes(%s)'}[e[2]] % bits(e[1])
    if not ir.is_op(e):
        return 'APInt(%s, UINT64_C(%d))' % (bits(e[1]), e[2])
    if e[0] == 'G_ZEXT':
        return '%s.zext(%s)' % (_cpp_const(e[2], bits), bits(e[1]))
    return _CPP_APINT[e[0]] % tuple(_cpp_const(a, bits) for a in e[2:])


def _cpp_recipe_checks(tgt, const_vars, bits):
    """The C++ conditions of smt.Encoder.recipe_guard, in the same order:
    each shift of a computed constant has an amount smaller than its
    width, and so has each shift whose amount is a computed constant."""
    out = []
    for c in ir.computed_constants(tgt, const_vars):
        for n in ir.nodes(c):
            if n[0] in ir.SHIFT_OPS:
                out.append('%s.ult(%s)' % (_cpp_const(n[3], bits),
                                           bits(n[1])))
    for w, c in ir.computed_amounts(tgt, const_vars):
        out.append('%s.ult(%s)' % (_cpp_const(c, bits), bits(w)))
    return out


def _bits_fn(rule):
    types = _type_sources(rule)

    def bits(w):
        return 'MRI.getType(%s).getScalarSizeInBits()' % _type_source(
            types, w)
    return bits


_KIND_NAME = {'f': 'floating-point', 'i': 'integer'}


def _type_source(types, w, kind=None, fmt='%s'):
    """The first register of ``types`` (see _type_sources) that has the
    width ``w`` and the kind ``kind`` ('f', 'i' or None: any). A register
    of an unknown kind can give the type of an integer, not the type of a
    floating-point value."""
    for tw, tk, reg in types:
        if tw == w and (kind is None or tk == kind or
                        (kind == 'i' and tk is None)):
            return fmt % reg
    if kind is None:
        raise ValueError('no operand with width %d' % w)
    raise ValueError('no %s operand with width %d' % (_KIND_NAME[kind], w))


def _check_kinds(src, tgt):
    """Raises ValueError if the types of the rule cannot be written: a
    value that is an integer and a floating-point value, or a
    floating-point constant (the patterns match and build G_CONSTANT)."""
    root_kind = ir.result_kind(src)
    kinds = ir.var_kinds(tgt, root_kind, ir.var_kinds(src))
    if 'x' in kinds.values():
        raise ValueError('a value is used as an integer and as a '
                         'floating-point value')
    return root_kind, kinds


def _apply_patterns(tgt, vw, root_w, src=None):
    """MIR apply patterns building ``tgt`` into $dst. ``src`` is the
    source pattern; it gives the kinds of the values."""
    root_kind, kinds = _check_kinds(src, tgt) if src is not None else \
        (None, {})
    if ir.is_var(tgt):
        return ['(GIReplaceReg $dst, $x%d)' % tgt[1]]
    if ir.is_lit(tgt):
        if root_kind == 'f':
            raise ValueError('a floating-point constant in the replacement')
        return ['(G_CONSTANT $dst, (GITypeOf<"$dst"> %s))' %
                _lit_imm(tgt[2])]
    pats = []
    n = [0]
    types = [(root_w, root_kind, 'dst')] + \
        [(w, kinds.get(i), 'x%d' % i) for i, w in enumerate(vw)]

    def type_of(w, kind):
        return _type_source(types, w, kind, 'GITypeOf<"$%s">')

    def walk(e, dst, kind):
        ops = []
        for k, a in enumerate(e[2:]):
            ak = ir.operand_kind(e, k, kind)
            if ir.is_var(a):
                ops.append('$x%d' % a[1])
            elif ir.is_lit(a):
                if ak == 'f':
                    raise ValueError('a floating-point constant in the '
                                     'replacement')
                ops.append('(%s %s)' % (type_of(a[1], ak), _lit_imm(a[2])))
            else:
                t = '$n%d' % n[0]
                n[0] += 1
                ak = ir.result_kind(a, ak)
                walk(a, '%s:%s' % (type_of(a[1], ak), t), ak)
                ops.append(t)
        pats.append('(%s %s, %s)' % (e[0], dst, ', '.join(ops)))

    walk(tgt, '$dst', ir.result_kind(tgt, root_kind))
    return pats


def _interior_kinds(src):
    """The kinds of the interior values of the source, in the order of
    _annotate."""
    out = []

    def walk(e, kind, root):
        if not ir.is_op(e):
            return
        kind = ir.result_kind(e, kind)
        if not root:
            out.append(kind)
        for k, a in enumerate(e[2:]):
            walk(a, ir.operand_kind(e, k, kind), False)
    walk(src, None, True)
    return out


def _type_sources(rule):
    """(width, kind, C++ expression of a register) of the values that a
    new value can take its type from: the root, the variables and the
    interior values of the source."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    _, interior = _annotate(src)
    root_kind, kinds = _check_kinds(src, tgt)
    return [(src[1], root_kind, 'Dst')] + \
        [(w, kinds.get(i), 'X%d' % i) for i, w in enumerate(rule['vw'])] + \
        [(w, k, 'T%d' % n)
         for n, (w, k) in enumerate(zip(interior, _interior_kinds(src)))]


def _apply_params(rule):
    _, interior = _annotate(ir.from_json(rule['source_json']))
    return ['Dst'] + ['X%d' % i for i in range(len(rule['vw']))] + \
        ['T%d' % k for k in range(len(interior))]


def _cpp_apply(rule):
    """The C++ function that builds the replacement before the root
    instruction and erases the root."""
    tgt = ir.from_json(rule['replacement_json'])
    cv = tuple(rule.get('const_vars', ()))
    types = _type_sources(rule)
    bits = _bits_fn(rule)
    # The guard checked that these are constants.
    body = ['  APInt C%d = *getIConstantVRegVal(X%d, MRI);' % (i, i)
            for i in cv]
    built = {}   # (instruction, operands) -> variable
    n = [0]

    src = ir.from_json(rule['source_json'])
    root_kind = ir.result_kind(src)

    def ty(w, kind=None):
        return _type_source(types, w, kind, 'MRI.getType(%s)')

    def no_fp_constant(kind):
        if kind == 'f':
            raise ValueError('a floating-point constant in the replacement')

    def new(text):
        name = 'N%d' % n[0]
        n[0] += 1
        body.append('  [[maybe_unused]] auto %s = %s;' % (name, text))
        return name

    outs = _region_outputs(rule)
    sib = _sibling(rule)
    if sib is not None:
        b, rb = sib
        sres = ops.parse(b[0])[2]
        if rb is None:
            # The instruction of the sibling is there: a node of the
            # replacement that is that instruction reads its results.
            built[_instr_key(b)] = 'NSib'
        else:
            outs = outs + [('SR%d' % sres, rb, ir.result_kind(b))]
    # (instruction, result) -> the register that the instruction defines:
    # the root and the old values of the other outputs.
    want = {}
    for dname, t in [('Dst', tgt)] + [(d, t) for d, t, _ in outs]:
        if ir.is_op(t) and not ir.is_constant_expr(t, cv) and \
                _instr_key(t) not in built:
            want.setdefault((_instr_key(t), ops.parse(t[0])[2]), dname)

    def walk(e, dst=None, kind=None):
        """Returns the C++ expression of the value of ``e``, which its
        user needs with the kind ``kind``."""
        if ir.is_var(e):
            return 'X%d' % e[1]
        if not ir.is_op(e):
            no_fp_constant(kind)
            v = ir.leaf_value(e)
            return new('B.buildConstant(%s, APInt(%d, UINT64_C(%d)))' %
                       (ty(e[1], kind), e[1], v)) + '.getReg(0)'
        if ir.is_constant_expr(e, cv):
            # A computed constant.
            no_fp_constant(kind)
            if e not in built:
                built[e] = new('B.buildConstant(%s, %s)' % (
                    dst or ty(e[1], kind), _cpp_const(e, bits)))
            return '%s.getReg(0)' % built[e]
        info, attr, res = ops.parse(e[0])
        kind = ir.result_kind(e, kind)
        args = [walk(a, None, ir.operand_kind(e, k, kind))
                for k, a in enumerate(e[2:])]
        key = _instr_key(e)
        if key not in built:
            # Each result of the instruction gets its type from the
            # operator: the main type or s1.
            if info.results == 1:
                rtys = [want.get((key, 0)) or ty(e[1], kind)]
            else:
                kinds = info.meta['result_kinds']
                mainw = ir.width(e[2], rule['vw'])
                rtys = [want.get((key, n)) or
                        (ty(mainw, 'i') if k == 'main' else ty(1, 'i'))
                        for n, k in enumerate(kinds)]
            if info.attr == 'pred':
                text = 'B.buildICmp(%s, %s, %s)' % (
                    _CPP_PRED[attr], rtys[0], ', '.join(args))
            else:
                srcs = list(args)
                if info.attr == 'imm':
                    srcs.append('int64_t(%d)' % attr)
                text = 'B.buildInstr(TargetOpcode::%s, {%s}, {%s})' % (
                    info.name, ', '.join(rtys), ', '.join(srcs))
            built[key] = new(text)
        return '%s.getReg(%d)' % (built[key], res)

    if not outs and sib is None:
        walk(tgt, 'Dst', root_kind)
    params = ['MachineIRBuilder &B', 'MachineInstr &Root'] + \
        ['Register %s' % p for p in _apply_params(rule)]
    head = ['  B.setInstrAndDebugLoc(Root);']
    tail = []
    if sib is not None:
        for dname, t, kind in [('Dst', tgt, root_kind)] + outs:
            v = walk(t, None, kind)
            if not ir.is_op(t) or ir.is_constant_expr(t, cv) or want.get(
                    (_instr_key(t), ops.parse(t[0])[2])) != dname:
                body.append('  B.buildCopy(%s, %s);' % (dname, v))
        # The sibling is found before a new instruction defines its
        # register. A sibling that stays is moved before the root if it
        # is after it; else the replacement is built before the first of
        # the two roots.
        head = ['  MachineInstr *Sib = %s(MRI, Root, %s);' % (
            _sibling_name(rule), ', '.join(_apply_params(rule)[1:]))] + [
            '  [[maybe_unused]] Register SR%d = Sib->getOperand(%d).getReg();'
            % (k, k) for k, _ in _sibling_results(b, rule['vw'])] + [
            '  B.setInstrAndDebugLoc(*siblingInsertPoint(Root, *Sib, {%s}, '
            '/*SibStays=*/%s, /*Move=*/true));' % (
                ', '.join('X%d' % v for v in _region_inputs(rule)),
                'true' if rb is None else 'false')]
        if rb is None:
            head.append('  [[maybe_unused]] MachineInstrBuilder NSib('
                        'B.getMF(), Sib);')
        else:
            tail = ['  Sib->eraseFromParent();']
    elif outs:
        # The replacement of an output below the root that is not the
        # result of a new instruction of its own is a copy.
        for dname, t, kind in [('Dst', tgt, root_kind)] + outs:
            v = walk(t, None, kind)
            if not ir.is_op(t) or ir.is_constant_expr(t, cv) or want.get(
                    (_instr_key(t), ops.parse(t[0])[2])) != dname:
                body.append('  B.buildCopy(%s, %s);' % (dname, v))
        # The old instructions are found before a new instruction defines
        # their registers, and the replacement is built before the first
        # of them: it then dominates the users of every output.
        head = ['  MachineInstr *Old%d = MRI.getVRegDef(%s);' % (n, d)
                for n, (d, _, _) in enumerate(outs)] + [
            '  B.setInstrAndDebugLoc(*firstRegionOutput(Root, {%s}, {%s}));'
            % (', '.join(d for d, _, _ in outs),
               ', '.join('X%d' % v for v in _region_inputs(rule)))]
        tail = ['  Old%d->eraseFromParent();' % n for n in range(len(outs))]
    out = ['/// Builds %s.' % rule['replacement'],
           'inline void %s(%s) {' % (_apply_name(rule), ', '.join(params)),
           '  [[maybe_unused]] MachineRegisterInfo &MRI = *B.getMRI();'] + \
        head + body + tail + ['  Root.eraseFromParent();', '}']
    return '\n'.join(out)


def why_not_emittable(rule):
    """None if the emitter can write the rule, else the reason."""
    src = ir.from_json(rule['source_json'])
    tgt = ir.from_json(rule['replacement_json'])
    cv = tuple(rule.get('const_vars', ()))
    if ops.parse(src[0])[0].results != 1:
        return 'the root instruction has several results'
    for n in [src] + ir.interior_nodes(src):
        info = ops.parse(n[0])[0]
        if info.shape not in ops._EMIT_SHAPES:
            return 'no match pattern for the shape %s' % info.shape
    # The guard reads a constant of the source with getIConstantVRegVal.
    src_kinds = ir.var_kinds(src)
    if any(src_kinds.get(v) == 'f' for v in cv):
        return 'a floating-point constant in the source'
    sib = _sibling(rule)
    there = set()
    if sib is not None:
        info = ops.parse(sib[0][0])[0]
        if info.shape not in ops._EMIT_SHAPES + ('unmerge',):
            return 'no match of a second root with the shape %s' % info.shape
        if info.meta.get('may_trap'):
            return 'a second root that can trap is not moved'
        if sib[1] is None:
            there.add(_instr_key(sib[0]))
    for n in [n for t in [tgt] + [t for _, t, _ in _region_outputs(rule)] +
              ([sib[1]] if sib is not None and sib[1] is not None else [])
              for n in ir.nodes(t)]:
        if _instr_key(n) in there:
            continue
        why = ops.capability(ops.parse(n[0])[0], 'emit')
        if why != 'yes':
            return '%s: %s' % (n[0], why)
    try:
        _annotate(src)
        _cpp_recipe_checks(tgt, cv, _bits_fn(rule))
        if _rule_needs_cpp_apply(rule):
            _cpp_apply(rule)
        else:
            _apply_patterns(tgt, rule['vw'], rule['source_json']['w'], src)
    except ValueError as e:
        return str(e)
    return None


def emittable(rule):
    return why_not_emittable(rule) is None


def _guard_name(rule):
    return 'guard_' + rule['id']


def _apply_name(rule):
    # A rule and its one-use variant have the same replacement.
    return 'apply_' + rule.get('variant_of', rule['id'])


TD_HEAD = [
    '//===- GISynthCombines.td - Synthesized combine rules ----*- '
    'tablegen -*-===//',
    '//',
    '// Part of the LLVM Project, under the Apache License v2.0 with '
    'LLVM Exceptions.',
    '// See https://llvm.org/LICENSE.txt for license information.',
    '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception',
    '//',
    '//===-------------------------------------------------------'
    '---------------===//',
    '//',
    '// ' + HEADER,
    '//',
    '// Every rule below was discovered from a gMIR corpus, '
    'generalized and',
    '// proved (bitvector refinement, see the rule library for the '
    'proof',
    '// records) by the offline synthesizer. The rules are target '
    'independent;',
    '// each target that hosts them has a group with the rules its '
    'profile',
    '// (llvm/utils/gisel-rule-synth/targets) selects. The guards live in',
    '// llvm/CodeGen/GlobalISel/GISynthGeneratedPredicates.inc.',
    '//',
    '//===-------------------------------------------------------'
    '---------------===//',
    '']


def emit_td(rules, sel):
    lines = list(TD_HEAD)
    names = {}
    for r in rules:
        vw = r['vw']
        tgt = ir.from_json(r['replacement_json'])
        root_w = r['source_json']['w']
        _, interior = _annotate(ir.from_json(r['source_json']))
        if _rule_needs_cpp_apply(r):
            apply_pats = ['[{ gisynth::%s(B, *${dst}.getParent(), %s); }]' % (
                _apply_name(r), ', '.join(
                    ['${dst}.getReg()'] +
                    ['${x%d}.getReg()' % i for i in range(len(vw))] +
                    ['${t%d}.getReg()' % k for k in range(len(interior))]))]
        else:
            apply_pats = _apply_patterns(tgt, vw, root_w,
                                         ir.from_json(r['source_json']))
        lines.append('// %s: %s -> %s' % (r['id'], r['source'],
                                          r['replacement']))
        lines.append('//   if %s' % r['precondition'])
        names[r['id']] = record_names(r)
        for name, pats in zip(names[r['id']], variants(r)):
            pats = list(pats)
            if r['needs_one_use']:
                pats += ['(GIHasOneUse $t%d)' % k
                         for k in range(len(interior))]
            args = ', '.join(['${dst}.getReg()'] +
                             ['${x%d}.getReg()' % i for i in range(len(vw))] +
                             ['${t%d}.getReg()' % k
                              for k in range(len(interior))])
            pats.append('[{ return gisynth::%s(MRI, Helper.getValueTracking(), '
                        '%s); }]' % (_guard_name(r), args))
            lines.append('def %s : GICombineRule<' % name)
            lines.append('  (defs root:$dst),')
            lines.append('  (match ' + ',\n         '.join(pats) + '),')
            lines.append('  (apply ' + ',\n         '.join(apply_pats) + ')>;')
        lines.append('')
    for tname in sorted(sel):
        recs = [n for r in sel[tname] for n in names[r['id']]]
        lines.append('// %s: %d rules, %d records.' %
                     (tname, len(sel[tname]), len(recs)))
        lines.append('def %s : GICombineGroup<[' %
                     targets.TARGETS[tname].group)
        for i in range(0, len(recs), 3):
            sep = ',' if i + 3 < len(recs) else ''
            lines.append('  ' + ', '.join(recs[i:i + 3]) + sep)
        lines.append(']>;')
        lines.append('')
    return '\n'.join(lines), names


def _cpp_guard(r):
    vw = r['vw']
    src = ir.from_json(r['source_json'])
    _, interior = _annotate(src)
    n, k = len(vw), len(interior)
    cols = list(vw) + interior + [src[1]]
    sib = _sibling(r)
    sres = _sibling_results(sib[0], vw) if sib is not None else []
    # A result of the sibling with a width of its own in every map (one
    # bit) is the column None.
    cols += [w for _, w in sres]
    dnf = rule_dnf(r)
    # Disjuncts that share their verified schedules share a table.
    tables, table_of = [], []
    # A rule that moves an operation to a wider type applies only at the
    # proved widths at which that type fits in a register of a target: a
    # wider operation is divided again by the target.
    wide = widened_bits(r)
    for d in r['disjuncts']:
        rows = sorted({tuple(1 if w is None else dict(m)[w] for w in cols)
                       for m in d['width_maps']
                       if not wide or dict(m)[wide] <= targets.NATIVE_BITS})
        # No width is left: a row that no register has.
        rows = rows or [(0,) * len(cols)]
        if rows not in tables:
            tables.append(rows)
        table_of.append(tables.index(rows))
    params = ['const MachineRegisterInfo &MRI', 'GISelValueTracking *VT',
              'Register Dst'] + ['Register X%d' % i for i in range(n)] + \
        ['Register T%d' % i for i in range(k)]
    regs = ['X%d' % i for i in range(n)] + ['T%d' % i for i in range(k)] + \
        ['Dst'] + ['SR%d' % i for i, _ in sres]
    what = ', '.join(['x%d' % i for i in range(n)] +
                     ['t%d' % i for i in range(k)] + ['root'] +
                     ['s%d' % i for i, _ in sres])
    out = ['/// %s -> %s' % (r['source'], r['replacement']),
           '/// if %s' % r['precondition']]
    for ti, rows in enumerate(tables):
        out.append('/// Proved for widths (%s)%s: %s.' % (
            what, '' if len(tables) == 1 else ' [V%d]' % ti,
            '; '.join(','.join(str(w) for w in row) for row in rows)))
    out += ['inline bool %s(%s) {' % (_guard_name(r), ', '.join(params)),
            '  DEBUG_WITH_TYPE("gisel-synth", dbgs() << "gisel-synth: '
            'matched: %s\\n");' % r['id']]
    if sib is not None:
        out += ['  // The second root of the region.',
                '  MachineInstr *Root = MRI.getVRegDef(Dst);',
                '  MachineInstr *Sib = Root ? %s(MRI, *Root, %s) : nullptr;'
                % (_sibling_name(r), ', '.join(
                    ['X%d' % i for i in range(n)] +
                    ['T%d' % i for i in range(k)])),
                '  if (!Sib)', '    return false;'] + [
            '  Register SR%d = Sib->getOperand(%d).getReg();' % (i, i)
            for i, _ in sres]
    out += ['  unsigned W[%d];' % len(cols),
            '  if (!getScalarWidths(MRI, {%s}, W))' % ', '.join(regs),
            '    return false;']
    for ti, rows in enumerate(tables):
        out.append('  static constexpr uint16_t V%d[][%d] = {%s};' % (
            ti, len(cols), ', '.join('{%s}' % ', '.join(str(w) for w in row)
                                     for row in rows)))
    single = len(tables) == 1
    if single:
        out += ['  if (!isVerifiedSchedule(W, V0))', '    return false;']
    else:
        for ti in range(len(tables)):
            out.append('  bool S%d = isVerifiedSchedule(W, V%d);' % (ti, ti))
        out += ['  if (!(%s))' % ' || '.join('S%d' % ti
                                             for ti in range(len(tables))),
                '    return false;']
    cv = tuple(r.get('const_vars', ()))
    if cv:
        out.append('  // The variables that the rule matches as constants, '
                   'and the conditions')
        out.append('  // on the computed constants of the replacement.')
    for i in cv:
        out += ['  std::optional<APInt> OptC%d = getIConstantVRegVal(X%d, '
                'MRI);' % (i, i),
                '  if (!OptC%d)' % i, '    return false;',
                '  [[maybe_unused]] const APInt &C%d = *OptC%d;' % (i, i)]
    for c in _cpp_recipe_checks(ir.from_json(r['replacement_json']), cv,
                                _bits_fn(r)):
        out += ['  if (!%s)' % c, '    return false;']
    cpp = [[precond.cpp_atom(a) for a in p] for p in dnf]
    text = ' '.join(c for p in cpp for c in p)
    for i in range(n):
        if ('W%d' % i) in text.replace('WRoot', ''):
            out.append('  [[maybe_unused]] unsigned W%d = W[%d];' % (i, i))
    if 'WRoot' in text:
        out.append('  [[maybe_unused]] unsigned WRoot = W[%d];' % (n + k))
    # Disjuncts without atoms need no value tracking; try them first.
    order = sorted(range(len(dnf)), key=lambda i: (bool(dnf[i]), i))
    have = set()
    first = True
    need_vt_check = True
    for i in order:
        sched = '' if single else 'S%d' % table_of[i]
        if not dnf[i]:
            cond = sched or 'true'
        else:
            cond = ' &&\n      '.join(([sched] if sched else []) + cpp[i])
        new = [v for v in precond.pred_vars(dnf[i]) if v not in have]
        have |= set(new)
        if dnf[i] and need_vt_check:
            need_vt_check = False
            if first:
                out += ['  if (!VT)', '    return false;']
            else:
                out += ['  if (!Pass && !VT)', '    return false;']
        if len(dnf) > 1:
            out.append('  // %s' % r['disjuncts'][i]['pred'])
        if first:
            for v in new:
                out.append('  KnownBits K%d = VT->getKnownBits(X%d);' %
                           (v, v))
            out.append('  bool Pass = %s;' % cond)
            first = False
        else:
            for v in new:
                out.append('  KnownBits K%d;' % v)
            out.append('  if (!Pass) {')
            for v in new:
                out.append('    K%d = VT->getKnownBits(X%d);' % (v, v))
            out.append('    Pass = %s;' % cond.replace('\n', '\n  '))
            out.append('  }')
    out += ['  if (!Pass)', '    return false;']
    if sib is not None:
        out += ['  // The replacement can be built: the two roots are near '
                'in one block,',
                '  // and the inputs are defined before the first of them.',
                '  if (!siblingInsertPoint(*Root, *Sib, {%s}, /*SibStays=*/%s'
                '))' % (', '.join('X%d' % v for v in _region_inputs(r)),
                        'true' if sib[1] is None else 'false'),
                '    return false;']
    elif r.get('region'):
        out += ['  // Each value below the root that the rule replaces has '
                'another user,',
                '  // and the replacement can be built before the first of '
                'them.',
                '  if (!isJointRegion(MRI, Dst, {%s}, {%s}))' % (
                    ', '.join(d for d, _, _ in _region_outputs(r)),
                    ', '.join('X%d' % v for v in _region_inputs(r))),
                '    return false;']
    out += ['  DEBUG_WITH_TYPE("gisel-synth", dbgs() << "gisel-synth: '
            'guard passed: %s\\n");' % r['id'],
            '  return true;', '}']
    return '\n'.join(out)


def emit_inc(rules, sel, names):
    lines = ['//===- GISynthGeneratedPredicates.inc - Synthesized guards ---*- '
             'C++ -*-===//',
             '//',
             '// Part of the LLVM Project, under the Apache License v2.0 with '
             'LLVM Exceptions.',
             '// See https://llvm.org/LICENSE.txt for license information.',
             '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '//',
             '// Generated by llvm/utils/gisel-rule-synth/gi-rule-synth.py '
             'from',
             '// llvm/utils/gisel-rule-synth/rules.json. DO NOT EDIT.',
             '// Included by llvm/CodeGen/GlobalISel/GISynthPredicates.h.',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '',
             '// Machine-generated; formatting is fixed by the emitter so '
             'that',
             '// `emit --check` stays byte-exact.',
             '// clang-format off',
             '']
    applies = set()
    finders = set()
    for r in rules:
        if _sibling(r) is not None and _sibling_name(r) not in finders:
            finders.add(_sibling_name(r))
            lines.append(_cpp_sibling(r))
            lines.append('')
        lines.append(_cpp_guard(r))
        lines.append('')
        if _rule_needs_cpp_apply(r) and _apply_name(r) not in applies:
            applies.add(_apply_name(r))
            lines.append(_cpp_apply(r))
            lines.append('')
    for tname in sorted(sel):
        lines.append('/// Records of the rules selected for %s, for enabling '
                     'them as a group.' % tname)
        lines.append('[[maybe_unused]] inline constexpr const char *%s[] = {'
                     % targets.TARGETS[tname].names_array)
        for r in sel[tname]:
            for nm in names[r['id']]:
                lines.append('    "%s",' % nm)
        if not sel[tname]:
            lines.append('    "",')
        lines.append('};')
        lines.append('')
    lines.append('// clang-format on')
    lines.append('')
    return '\n'.join(lines)


def emit(db, profiles=None, all_candidates=False):
    """Returns (td text, inc text, info)."""
    sel = selection(db, profiles or {}, all_candidates)
    sel = {t: [r for r in rs if emittable(r)] for t, rs in sel.items()}
    ids = {r['id'] for rs in sel.values() for r in rs}
    rules = [r for r in candidates(db) if r['id'] in ids]
    td, names = emit_td(rules, sel)
    inc = emit_inc(rules, sel, names)
    info = {'rules': len(rules),
            'records': sum(len(n) for n in names.values()),
            'forms_before_dedup': sum(
                len(ir.commuted_variants(ir.from_json(r['source_json'])))
                for r in rules),
            'targets': {t: {'rules': len(rs),
                            'records': sum(len(names[r['id']]) for r in rs)}
                        for t, rs in sel.items()}}
    return td, inc, info
