"""TableGen / C++ emission from the verified rule database.

Only rules with semantic_status.kind == 'verified_refinement' and a strictly
cheaper replacement are emitted. For each rule the emitter writes

* one GICombineRule per distinct commuted form of the source pattern (the
  GlobalISel combiner does not try commuted operands on its own), matching
  the source with MIR patterns, checking interior one-use when the
  replacement creates instructions, and calling a generated guard;
* one inline C++ guard that checks the operand widths against the verified
  width schedules and evaluates the synthesized known-bits precondition with
  GISelValueTracking.

Nothing here runs a solver: emission is a pure function of the database, so
`gi-rule-synth.py emit --check` can detect stale generated files.
"""

from . import ir
from . import precond

HEADER = ('Generated by llvm/utils/gisel-rule-synth/gi-rule-synth.py from '
          'llvm/utils/gisel-rule-synth/rules.json. DO NOT EDIT.')


def emitted_rules(db):
    out = []
    for r in db['rules']:
        if r['semantic_status']['kind'] != 'verified_refinement':
            continue
        if r['cost']['replacement'] >= r['cost']['source']:
            continue
        if r.get('selection', 'emitted') != 'emitted':
            continue
        out.append(r)
    # Smaller source patterns first: they have priority in the combiner.
    out.sort(key=lambda r: (r['cost']['source'], r['id']))
    return out


class _Names:
    def __init__(self):
        self.n = 0

    def fresh(self, prefix):
        self.n += 1
        return '$%s%d' % (prefix, self.n - 1)


def _match_patterns(src):
    """MIR match patterns for a source tree, operands defined first.
    Returns (patterns, interior temp names)."""
    pats, temps = [], []
    names = _Names()

    def walk(e, dst):
        ops = []
        for a in e[2:]:
            if ir.is_var(a):
                ops.append('$x%d' % a[1])
            elif ir.is_lit(a):
                raise ValueError('literal in source pattern')
            else:
                t = names.fresh('t')
                temps.append(t)
                walk(a, t)
                ops.append(t)
        pats.append('(%s %s, %s)' % (e[0], dst, ', '.join(ops)))

    walk(src, '$dst')
    return pats, temps


def _lit_imm(k):
    return {'0': '0', '1': '1', '-1': '-1'}[k]


def _apply_patterns(tgt, vw, root_w):
    """MIR apply patterns building ``tgt`` into $dst."""
    if ir.is_var(tgt):
        return ['(GIReplaceReg $dst, $x%d)' % tgt[1]]
    if ir.is_lit(tgt):
        return ['(G_CONSTANT $dst, (GITypeOf<"$dst"> %s))' %
                _lit_imm(tgt[2])]
    pats = []
    names = _Names()

    def type_of(w):
        if w == root_w:
            return 'GITypeOf<"$dst">'
        for i, vwi in enumerate(vw):
            if vwi == w:
                return 'GITypeOf<"$x%d">' % i
        raise ValueError('no operand with width %d' % w)

    def walk(e, dst):
        ops = []
        for a in e[2:]:
            if ir.is_var(a):
                ops.append('$x%d' % a[1])
            elif ir.is_lit(a):
                ops.append('(%s %s)' % (type_of(a[1]), _lit_imm(a[2])))
            else:
                t = names.fresh('n')
                walk(a, '%s:%s' % (type_of(a[1]), t))
                ops.append(t)
        pats.append('(%s %s, %s)' % (e[0], dst, ', '.join(ops)))

    walk(tgt, '$dst')
    return pats


def _variants(rule):
    """Distinct commuted forms of the source, each with its own variable
    order (patterns are written with the canonical variable names)."""
    src = ir.from_json(rule['source_json'])
    return ir.commuted_variants(src)


def _guard_name(rule):
    return 'guard_' + rule['id']


def emit_td(db):
    rules = emitted_rules(db)
    lines = ['//===- GISynthCombines.td - Synthesized combine rules ----*- '
             'tablegen -*-===//',
             '//',
             '// Part of the LLVM Project, under the Apache License v2.0 with '
             'LLVM Exceptions.',
             '// See https://llvm.org/LICENSE.txt for license information.',
             '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '//',
             '// ' + HEADER,
             '//',
             '// Every rule below was discovered from a gMIR corpus, '
             'generalized and',
             '// proved (bitvector refinement, see the rule database for the '
             'proof',
             '// records) by the offline synthesizer. The guards live in',
             '// llvm/CodeGen/GlobalISel/GISynthGeneratedPredicates.inc.',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '']
    names, ids = [], []
    for r in rules:
        vw = r['vw']
        tgt = ir.from_json(r['replacement_json'])
        root_w = r['source_json']['w']
        try:
            apply_pats = _apply_patterns(tgt, vw, root_w)
        except ValueError:
            continue
        ids.append(r['id'])
        lines.append('// %s: %s -> %s' % (r['id'], r['source'],
                                          r['replacement']))
        lines.append('//   if %s' % r['precondition'])
        for k, v in enumerate(_variants(r)):
            name = r['id'] if k == 0 else '%s_c%d' % (r['id'], k)
            names.append(name)
            pats, temps = _match_patterns(v)
            if r['needs_one_use']:
                pats += ['(GIHasOneUse %s)' % t for t in temps]
            args = ', '.join(['${dst}.getReg()'] +
                             ['${x%d}.getReg()' % i for i in range(len(vw))])
            pats.append('[{ return gisynth::%s(MRI, Helper.getValueTracking(), '
                        '%s); }]' % (_guard_name(r), args))
            lines.append('def %s : GICombineRule<' % name)
            lines.append('  (defs root:$dst),')
            lines.append('  (match ' + ',\n         '.join(pats) + '),')
            lines.append('  (apply ' + ',\n         '.join(apply_pats) + ')>;')
        lines.append('')
    lines.append('def gi_synth_combines : GICombineGroup<[')
    for i in range(0, len(names), 3):
        sep = ',' if i + 3 < len(names) else ''
        lines.append('  ' + ', '.join(names[i:i + 3]) + sep)
    lines.append(']>;')
    lines.append('')
    return '\n'.join(lines), names, ids


def _cpp_guard(r):
    vw = r['vw']
    pred = tuple(precond.atom_from_json(a) for a in r['precondition_json'])
    sched = r['semantic_status']['schedules']
    n = len(vw)
    used = sorted({i for a in pred for i in _atom_vars(a)})
    params = ['const MachineRegisterInfo &MRI', 'GISelValueTracking *VT',
              'Register Dst'] + ['Register X%d' % i for i in range(n)]
    out = ['/// %s -> %s' % (r['source'], r['replacement']),
           '/// if %s' % r['precondition'],
           '/// Proved for widths (x0..x%d, root): %s.' %
           (n - 1, '; '.join(','.join(str(w) for w in s) for s in sched)),
           'inline bool %s(%s) {' % (_guard_name(r), ', '.join(params)),
           '  static constexpr uint16_t Verified[][%d] = {%s};' %
           (n + 1, ', '.join('{%s}' % ', '.join(str(w) for w in s)
                             for s in sched)),
           '  unsigned W[%d];' % (n + 1),
           '  if (!getScalarWidths(MRI, {%s}, W) ||' %
           ', '.join(['X%d' % i for i in range(n)] + ['Dst']),
           '      !isVerifiedSchedule(W, Verified))',
           '    return false;']
    if pred:
        out.append('  if (!VT)')
        out.append('    return false;')
    for i in range(n):
        if any(('W%d' % i) in precond.cpp_atom(a) for a in pred):
            out.append('  [[maybe_unused]] unsigned W%d = W[%d];' % (i, i))
    if any('WRoot' in precond.cpp_atom(a) for a in pred):
        out.append('  [[maybe_unused]] unsigned WRoot = W[%d];' % n)
    for i in used:
        out.append('  KnownBits K%d = VT->getKnownBits(X%d);' % (i, i))
    if pred:
        out.append('  if (!(' + ' &&\n        '.join(
            precond.cpp_atom(a) for a in pred) + '))')
        out.append('    return false;')
    out.append('  DEBUG_WITH_TYPE("gisel-synth", dbgs() << "gisel-synth: '
               'guard passed: %s\\n");' % r['id'])
    out.append('  return true;')
    out.append('}')
    return '\n'.join(out)


def _atom_vars(a):
    k = a[0]
    if k in ('all', 'msb'):
        return [a[1][1]]
    if k == 'all2':
        return [a[1][1], a[2][1]]
    if k in ('lowones', 'hiones'):
        return [a[1][1]]
    if k in ('lead', 'trail'):
        return [a[1][1], a[2]]
    return [a[1], a[2]]


def emit_inc(db, names, ids):
    rules = emitted_rules(db)
    lines = ['//===- GISynthGeneratedPredicates.inc - Synthesized guards ---*- '
             'C++ -*-===//',
             '//',
             '// Part of the LLVM Project, under the Apache License v2.0 with '
             'LLVM Exceptions.',
             '// See https://llvm.org/LICENSE.txt for license information.',
             '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '//',
             '// Generated by llvm/utils/gisel-rule-synth/gi-rule-synth.py '
             'from',
             '// llvm/utils/gisel-rule-synth/rules.json. DO NOT EDIT.',
             '// Included by llvm/CodeGen/GlobalISel/GISynthPredicates.h.',
             '//',
             '//===-------------------------------------------------------'
             '---------------===//',
             '',
             '// Machine-generated; formatting is fixed by the emitter so '
             'that',
             '// `emit --check` stays byte-exact.',
             '// clang-format off',
             '']
    for r in rules:
        if r['id'] not in ids:
            continue
        lines.append(_cpp_guard(r))
        lines.append('')
    lines.append('/// Names of all synthesized rules, for enabling them as a '
                 'group.')
    lines.append('inline constexpr const char *SynthRuleNames[] = {')
    for n in names:
        lines.append('    "%s",' % n)
    lines.append('};')
    lines.append('// clang-format on')
    lines.append('')
    return '\n'.join(lines)


def emit(db):
    td, names, ids = emit_td(db)
    return td, emit_inc(db, names, ids)
